def count_lines(path):
    n = 0
    with io.open(path, 'rb') as f:
        for _ in f:
            n += 1
    return n


def resolve_src(src_dir, candidates):
    """候选源名按序找，返回首个存在的路径；都无则 None。
    Try candidate source names in order, returning the path of the first that exists; None if none exist."""
    for name in candidates:
        p = os.path.join(src_dir, name)
        if os.path.exists(p):
            return p
    return None


def plan_for(spec, src):
    """按包定义算出 [(源路径, 目标名)] 与缺件清单（build_one 与 verify_one 共用）。
    Compute [(source path, target name)] and the missing-file list from the package definition (shared by build_one and verify_one)."""
    plan = []  # [(src_path, dst_name)] / [(源路径, 目标名)]
    missing = []
    flat = (spec.get('prog', []) + spec.get('prog_aux', [])
            + spec.get('conf', []) + spec.get('doc', [])
            + spec.get('sub', []))
    for f in flat:
        sp = os.path.join(src, f)
        if not os.path.exists(sp):
            missing.append(f)
        else:
            plan.append((sp, f))
    for candidates, dst_name in (spec.get('conf_rename', [])
                                 + spec.get('doc_rename', [])):
        sp = resolve_src(src, candidates)
        if sp is None:
            missing.append(candidates[0])
        else:
            plan.append((sp, dst_name))
    return plan, missing


def md5_of(path):
    h = hashlib.md5()
    with io.open(path, 'rb') as f:
        for chunk in iter(lambda: f.read(65536), b''):
            h.update(chunk)
    return h.hexdigest()


def verify_one(pkg_key, spec, src, out_root):
    """逐件比对「产物 == 源」md5；返回失配清单 [(盒, 件, 因)]。
    Compare the md5 of "artifact == source" file by file; return the mismatch list [(box, file, reason)]."""
    box = spec['box']
    dest = os.path.join(out_root, box)
    plan, missing = plan_for(spec, src)
    bad = [(box, f, '源缺件') for f in missing]
    for sp, dn in plan:
        dp = os.path.join(dest, dn)
        if not os.path.exists(dp):
            bad.append((box, dn, '产物缺'))
        elif md5_of(sp) != md5_of(dp):
            bad.append((box, dn, '产物≠源'))
    return bad


def verify_all(targets, src, out_root):
    """一致守卫：逐包逐件比对「产物 == 源」md5；全同返 0，失配返 3。
    （承 W-DB-026 丁·防「改了产物不落源·重打包静默抹」）
    Consistency guard: compare the md5 of "artifact == source" package by package, file by file; return 0 if all match, 3 on mismatch.
    (Per W-DB-026 D · guards against "editing the artifact without landing it in the source · repacking silently wipes it")"""
    print('== 一致守卫：产物 == 源 校验 ==')
    bad = []
    for name in targets:
        bad += verify_one(name, PACKAGES[name], src, out_root)
    if bad:
        print('  失配 %d 件（产物已偏离源）：' % len(bad), file=sys.stderr)
        for box, dn, why in bad:
            print('    ✗ %-14s %-26s %s' % (box + '/', dn, why), file=sys.stderr)
        print('  ⇒ 源为唯一改动点：请把改动落回源，再重打包。', file=sys.stderr)
        return 3
    print('  全同 ✓（%d 包逐件比对通过）' % len(targets))
    return 0


def build_one(pkg_key, spec, src, out_root, dry=False):
    box = spec['box']
    dest = os.path.join(out_root, box)
    print('== %s （盒 %s/）==' % (pkg_key, box))
    plan, missing = plan_for(spec, src)
    if missing:
        print('  缺件：%s' % '、'.join(missing), file=sys.stderr)
        return 2

    prog_files = spec.get('prog', [])
    total = sum(count_lines(os.path.join(src, f)) for f in prog_files)
    print('  版本号 v%s（语义）｜构建号 %d（＝本包 %d 个产品 .py 件行数之和）'
          % (SUITE_VERSION, total, len(prog_files)))
    for f in prog_files:
        print('    %-26s %5d 行' % (f, count_lines(os.path.join(src, f))))

    if dry:
        print('  (dry·不拷贝)')
        return 0

    if os.path.exists(dest):
        shutil.rmtree(dest)   # 仅删本包目录（产物·可删，承 §八）；不动根与源
                              # delete only this package's directory (an artifact · safe to delete, per §8); never the root or the source
    os.makedirs(dest)
    for sp, dn in plan:
        dp = os.path.join(dest, dn)
        sub = os.path.dirname(dp)
        if sub and not os.path.isdir(sub):
            os.makedirs(sub)          # sub 类目（如 sample/）·支持子路径件
                                      # sub category (e.g. sample/) · supports sub-path files
        shutil.copy2(sp, dp)
    # ── 清运行时残留件（防发布包带垃圾·承 #360 小债）──
    # ── Clean up runtime leftovers (keeps junk out of the release package · per #360 minor debt) ──
    # daybook.py index 产生 volumes.md / index_* / multilevel/；safeio 产生 .safeio_lock.*
    # daybook.py index produces volumes.md / index_* / multilevel/; safeio produces .safeio_lock.*
    # 这些是运行时产物·不应随发布包发出·每次打包都清一遍
    # These are runtime artifacts · should not ship with the release package · cleaned on every pack
    for pat in ('.safeio_lock.*', 'volumes.md', 'index_*', '*.pyc'):
        for pp in glob.glob(os.path.join(dest, pat)):
            try:
                os.remove(pp)
            except OSError:
                pass
    for pp in glob.glob(os.path.join(dest, '__pycache__')):
        shutil.rmtree(pp, ignore_errors=True)   # 承 #470 观察②·清缓存目录
                                                # per #470 observation ② · remove the cache directory
    for d in ('multilevel', '多级'):                          # v3.1·多级目录为运行时派生件·不随包发
                                                              # v3.1 · multi-level directories are runtime-derived artifacts · not shipped
        dp = os.path.join(dest, d)
        if os.path.isdir(dp):
            shutil.rmtree(dp, ignore_errors=True)
    with io.open(os.path.join(dest, 'version.txt'), 'w', encoding='utf-8') as f:
        f.write('daybook-suite v%s · %s\n'
                '版本号 v%s（语义版本·三包同源同发·统一）\n'
                '构建号 %d（＝本包 %d 个产品 .py 件行数之和·构建指纹·非版本号）\n'
                '口径与复现：见仓根 README「版本号与构建号」；复现命令 python3 src/pack.py --dry\n'
                '生成于 %s\n'
                % (SUITE_VERSION, box, SUITE_VERSION, total, len(prog_files),
                   time.strftime('%Y-%m-%d %H:%M')))
    print('  已生成：%s' % dest)
    return 0


def main():
    ap = argparse.ArgumentParser(description='daybook-suite 三包打包器')
    ap.add_argument('--src', default=HERE, help='源码目录（默认脚本所在）')
    ap.add_argument('--out', default=os.path.dirname(HERE),
                    help='产出根目录（默认源目录之上一级＝suite 根）')
    ap.add_argument('--pkg', choices=['daybook', 'mcp', 'orch', 'all'], default='all',
                    help='打哪个包（默认 all）')
    ap.add_argument('--dry', action='store_true', help='只算与列清单，不拷贝')
    ap.add_argument('--verify', action='store_true',
                    help='不拷贝·只逐件比对「产物 == 源」md5（失配即非零退出）')
    args = ap.parse_args()

    src = os.path.abspath(args.src)
    out_root = os.path.abspath(os.path.expanduser(args.out))
    targets = list(PACKAGES) if args.pkg == 'all' else [args.pkg]

    if args.verify:
        return verify_all(targets, src, out_root)

    rc = 0
    for name in targets:
        r = build_one(name, PACKAGES[name], src, out_root, dry=args.dry)
        if r:
            rc = r
    if not rc and not args.dry:
        if args.pkg == 'all':
            print('三包已生成于：%s' % out_root)
            print('自验：')
            print('  cd "%s/daybook"      && python3 daybook.py index' % out_root)
            print('  cd "%s/daybook-orch" && python3 orchestrator.py selftest' % out_root)
        vrc = verify_all(targets, src, out_root)   # 一致守卫（承 W-DB-026 丁）
                                                   # consistency guard (per W-DB-026 D)
        if vrc:
            rc = vrc
    return rc


if __name__ == '__main__':
    sys.exit(main())
